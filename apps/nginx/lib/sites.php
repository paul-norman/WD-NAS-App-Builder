<?php
// Generates Nginx's sites for the proxied apps (sites/60-app-<name>.conf), the user's sites set up on the page (sites/
// 50-site-<name>.conf), the start page (sites/00-app-start.conf and www/start/index.html), and a temporary self-signed
// certificate. Used by the management page, and by init.sh through
// the NAS's own PHP CLI (WD's PHP 7.4, or the PHP app's 8.5), so it must work on both:
//     php sites.php generate <data path>
//     php sites.php selfsigned <data path>
// Settings live in <data path>/apps.json; sites written by the app start with SITES_MARKER, and only those are ever
// replaced or removed - everything else in sites/ belongs to the user.

const SITES_MARKER = '# Generated by the Nginx app (from its page in the NAS dashboard) - changes here are overwritten';

// The apps offered by default, when installed (their folder in Nas_Prog): name => [label, target, options]
function sites_known_apps()
{
	return [
		'jellyfin' => ['folder' => 'jellyfin', 'label' => 'Jellyfin', 'target' => 'http://127.0.0.1:8096'],
		// (reachable on 127.0.0.1 because the Docker app turns off Docker's docker-proxy, which doesn't work on WD's NAS)
		'portainer' => ['folder' => 'docker', 'label' => 'Portainer (Docker)', 'target' => 'http://127.0.0.1:9000'],
		'mailpit' => ['folder' => 'mailpit', 'label' => 'Mailpit', 'target' => 'http://127.0.0.1:8025'],
		// Syncthing refuses other Host names (to stop DNS rebinding attacks)
		'syncthing' => ['folder' => 'syncthing', 'label' => 'Syncthing', 'target' => 'http://127.0.0.1:8384', 'host' => 'localhost'],
		'plex' => ['folder' => 'plexmediaserver', 'label' => 'Plex', 'target' => 'http://127.0.0.1:32400'],
		// (the Vaultwarden app finds its address by this target, so it still works if the site is renamed)
		'vaultwarden' => ['folder' => 'vaultwarden', 'label' => 'Vaultwarden', 'target' => 'http://127.0.0.1:8222'],
		// Served by the NAS's own web server, under a path
		'phpmyadmin' => ['folder' => 'phpMyAdmin', 'label' => 'phpMyAdmin', 'target' => 'http://127.0.0.1:80', 'path' => '/phpMyAdmin/'],
	];
}

// The settings, with the installed apps that aren't listed yet added (switched on)
function sites_load($data_path)
{
	$settings = json_decode((string)@file_get_contents($data_path . '/apps.json'), true);
	if (!is_array($settings)) {
		$settings = [];
	}
	$settings += ['domain' => '', 'apps' => [], 'sites' => []];
	$listed = [];
	foreach ($settings['apps'] as $app) {
		$listed[$app['name']] = true;
	}
	$apps_path = dirname($data_path);
	foreach (sites_known_apps() as $name => $known) {
		if (!isset($listed[$name]) && is_dir($apps_path . '/' . $known['folder'])) {
			$settings['apps'][] = [
				'name' => $name,
				'label' => $known['label'],
				'target' => $known['target'],
				'host' => isset($known['host']) ? $known['host'] : '',
				'path' => isset($known['path']) ? $known['path'] : '',
				'enabled' => true,
			];
		}
	}
	return $settings;
}

// Checks one app's settings, returning an error message (or '')
function sites_check_app(array $app)
{
	if (!preg_match('/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/', $app['name'])) {
		return 'Names are lower case letters, digits and - (e.g. jellyfin): ' . $app['name'];
	}
	if (!preg_match('#^https?://[A-Za-z0-9.-]+(:\d{1,5})?$#', $app['target'])) {
		return 'Targets are an address and port, e.g. http://127.0.0.1:8096 (for ' . $app['name'] . ')';
	}
	if ($app['host'] !== '' && !preg_match('/^[A-Za-z0-9.-]+(:\d{1,5})?$/', $app['host'])) {
		return 'Not a host name, for ' . $app['name'] . ': ' . $app['host'];
	}
	if ($app['path'] !== '' && !preg_match('#^/[A-Za-z0-9._~/-]*/$#', $app['path'])) {
		return 'Paths start and end with /, e.g. /phpMyAdmin/ (for ' . $app['name'] . ')';
	}
	if (mb_strlen($app['label']) > 60 || preg_match('/[\x00-\x1f]/', $app['label'])) {
		return 'Labels are up to 60 characters, for ' . $app['name'];
	}
	return '';
}

// Checks one site's settings (a folder on the NAS's volumes or USB drives), returning an error message (or '')
function sites_check_site(array $site)
{
	if (!preg_match('/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/', $site['name'])) {
		return 'Names are lower case letters, digits and - (e.g. blog): ' . $site['name'];
	}
	// (no quotes, ; { } $ or \, which would break out of Nginx's configuration)
	if (!preg_match('#^/(mnt/HD|mnt/USB|shares)/[^"\';{}$\\\\\x00-\x1f]+$#', $site['root'])) {
		return 'Folders are on the NAS\'s volumes or USB drives, e.g. /mnt/HD/HD_a2/Web/blog (for ' . $site['name'] . ')';
	}
	if (!is_dir($site['root'])) {
		return 'No such folder, for ' . $site['name'] . ': ' . $site['root'];
	}
	// Where it really is (e.g. not /mnt/HD/../etc)
	if (!preg_match('#^/(mnt/HD|mnt/USB)/#', realpath($site['root']) . '/')) {
		return 'Folders are on the NAS\'s volumes or USB drives, for ' . $site['name'] . ': ' . $site['root'];
	}
	if (mb_strlen($site['label']) > 60 || preg_match('/[\x00-\x1f]/', $site['label'])) {
		return 'Labels are up to 60 characters, for ' . $site['name'];
	}
	return '';
}

function sites_check_domain($domain)
{
	return preg_match('/^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/', $domain) ? '' : 'Not a domain name (e.g. example.com or nas.example.com): ' . $domain;
}

// Writes a file in one step (a temporary file renamed over it)
function sites_write($file, $contents)
{
	$temp = $file . '.tmp';
	return file_put_contents($temp, $contents) !== false && rename($temp, $file);
}

// One app's site
function sites_app_conf(array $app, $domain)
{
	$host = $app['host'] !== '' ? $app['host'] : '$host';
	$proxy = "        include          server.d/proxy.conf;\n"
		. "        proxy_set_header Host {$host};\n"
		. "        proxy_pass       {$app['target']};\n";
	$locations = $app['path'] === ''
		? "    location / {\n{$proxy}    }\n"
		: "    location = / {\n        return 302 {$app['path']};\n    }\n\n    location {$app['path']} {\n{$proxy}    }\n";
	return SITES_MARKER . "\n# {$app['label']}\n\nserver {\n"
		. "    include     server.d/https.conf;\n"
		. "    server_name {$app['name']}.{$domain};\n\n"
		. $locations . "}\n";
}

// One of the user's sites: its folder, with PHP (or with PHP files refused, so that their source is never shown), and
// optionally with every unknown path going to index.php (front controllers, e.g. Laravel, WordPress)
function sites_site_conf(array $site, $domain)
{
	$root = rtrim($site['root'], '/');
	$fallback = $site['php'] && $site['front'] ? '/index.php?$query_string' : '=404';
	return SITES_MARKER . "\n# {$site['label']}\n\nserver {\n"
		. "    include     server.d/https.conf;\n"
		. "    server_name {$site['name']}.{$domain};\n"
		. "    root        \"{$root}\";\n"
		. '    index       ' . ($site['php'] ? 'index.php ' : '') . "index.html index.htm;\n\n"
		. "    include     server.d/hidden.conf;\n"
		. "    include     server.d/log-exclusions.conf;\n"
		. '    include     server.d/' . ($site['php'] ? 'php.conf' : 'php-off.conf') . ";\n\n"
		. "    location / {\n        try_files \$uri \$uri/ {$fallback};\n    }\n}\n";
}

// The start page's site: also the default for any other name, and where HTTP/3's reuseport is set (only allowed once)
function sites_start_conf($domain, $data_path)
{
	$names = $domain !== '' ? $domain . ' ' : '';
	return SITES_MARKER . "\n# The start page, listing the apps (and the answer for any name without a site)\n\nserver {\n"
		. "    listen      443 ssl default_server;\n"
		. "    listen      443 quic reuseport default_server;\n"
		. "    http2       on;\n"
		. "    add_header  Alt-Svc 'h3=\":443\"; ma=86400' always;\n"
		. "    server_name {$names}_;\n"
		. "    root        {$data_path}/www/start;\n"
		. "    index       index.html;\n\n"
		. "    include     ssl.d/default.conf;\n"
		. "    include     server.d/hidden.conf;\n"
		. "    include     server.d/log-exclusions.conf;\n\n"
		. "    location / {\n        try_files \$uri \$uri/ =404;\n    }\n}\n";
}

function sites_start_html(array $settings)
{
	$h = function ($text) {
		return htmlspecialchars($text, ENT_QUOTES, 'UTF-8');
	};
	$links = '';
	foreach (array_merge($settings['apps'], $settings['sites']) as $app) {
		if ($app['enabled'] && $settings['domain'] !== '') {
			$url = 'https://' . $app['name'] . '.' . $settings['domain'] . '/';
			$links .= "\t\t<li><a href=\"" . $h($url) . '"><strong>' . $h($app['label']) . '</strong><span>' . $h($url) . "</span></a></li>\n";
		}
	}
	if ($links === '') {
		$links = "\t\t<li class=\"none\">No apps or sites yet: add them on the Nginx app's page in the NAS dashboard.</li>\n";
	}
	return <<<HTML
<!doctype html>
<html lang="en">
<head>
	<meta charset="utf-8">
	<meta name="viewport" content="width=device-width, initial-scale=1">
	<title>Apps</title>
	<style>
		:root { --bg: #f4f5f7; --card: #fff; --text: #1d2330; --muted: #69707d; --accent: #2f6fdb; }
		@media (prefers-color-scheme: dark) { :root { --bg: #15181e; --card: #1f242c; --text: #e6e8eb; --muted: #9aa1ac; --accent: #6ea0ff; } }
		body { margin: 0; padding: 2rem 1rem; background: var(--bg); color: var(--text); font: 16px/1.5 system-ui, sans-serif; }
		main { max-width: 40rem; margin: 0 auto; }
		h1 { font-size: 1.4rem; margin: 0 0 1rem; }
		ul { list-style: none; margin: 0; padding: 0; display: grid; gap: 0.6rem; }
		a { display: block; padding: 0.8rem 1rem; background: var(--card); border-radius: 8px; color: inherit; text-decoration: none; box-shadow: 0 1px 2px rgba(0, 0, 0, 0.08); }
		a:hover strong { color: var(--accent); }
		span { display: block; color: var(--muted); font-size: 0.85rem; word-break: break-all; }
		.none { color: var(--muted); }
	</style>
</head>
<body>
	<main>
		<h1>Apps</h1>
		<ul>
{$links}		</ul>
	</main>
</body>
</html>

HTML;
}

// The user's own sites: the names in the server_name lines of sites/*.conf that the app didn't generate (skipping
// wildcards, regular expressions and the catch-all _)
function sites_own_names($data_path)
{
	$names = [];
	foreach (glob($data_path . '/sites/*.conf') ?: [] as $file) {
		$conf = (string)file_get_contents($file);
		if (strpos($conf, SITES_MARKER) === 0) {
			continue;
		}
		preg_match_all('/^\s*server_name\s+([^;]+);/m', $conf, $m);
		foreach ($m[1] as $list) {
			foreach (preg_split('/\s+/', trim($list)) as $name) {
				if (preg_match('/^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/i', $name)) {
					$names[strtolower($name)] = basename($file);
				}
			}
		}
	}
	return $names;
}

// Writes every generated site and the start page, removing generated sites that are no longer wanted. Returns '' or an
// error message
function sites_generate($data_path)
{
	$settings = sites_load($data_path);
	$sites = $data_path . '/sites';
	if (!is_dir($sites) || !is_dir($data_path . '/www/start') && !mkdir($data_path . '/www/start', 0755, true)) {
		return 'Missing folder: ' . $sites;
	}

	$wanted = ['00-app-start.conf' => sites_start_conf($settings['domain'], $data_path)];
	if ($settings['domain'] !== '') {
		foreach ($settings['apps'] as $app) {
			if ($app['enabled'] && sites_check_app($app) === '') {
				$wanted['60-app-' . $app['name'] . '.conf'] = sites_app_conf($app, $settings['domain']);
			}
		}
		foreach ($settings['sites'] as $site) {
			if ($site['enabled'] && sites_check_site($site) === '') {
				$wanted['50-site-' . $site['name'] . '.conf'] = sites_site_conf($site, $settings['domain']);
			}
		}
	}
	foreach (glob($sites . '/*.conf') ?: [] as $file) {
		if (!isset($wanted[basename($file)]) && strpos((string)file_get_contents($file, false, null, 0, 200), SITES_MARKER) === 0) {
			unlink($file);
		}
	}
	foreach ($wanted as $name => $contents) {
		$file = $sites . '/' . $name;
		// Never overwrite a file the user made (without the marker) under the same name
		if (is_file($file) && strpos((string)file_get_contents($file, false, null, 0, 200), SITES_MARKER) !== 0) {
			continue;
		}
		if (!sites_write($file, $contents)) {
			return 'Could not write: ' . $file;
		}
	}
	return sites_write($data_path . '/www/start/index.html', sites_start_html($settings)) ? '' : 'Could not write the start page';
}

// A temporary self-signed certificate, so that Nginx can start before a real one is set up
function sites_selfsigned($data_path, $name = 'nas.local')
{
	$key = openssl_pkey_new(['private_key_type' => OPENSSL_KEYTYPE_EC, 'curve_name' => 'prime256v1']);
	$config = tempnam(sys_get_temp_dir(), 'ssl');
	file_put_contents($config, "[req]\ndistinguished_name=dn\n[dn]\n[ext]\nsubjectAltName=DNS:{$name}\nbasicConstraints=CA:FALSE\n");
	$options = ['config' => $config, 'digest_alg' => 'sha256', 'x509_extensions' => 'ext'];
	$csr = openssl_csr_new(['commonName' => $name], $key, $options);
	$cert = $csr ? openssl_csr_sign($csr, null, $key, 825, $options, random_int(1, PHP_INT_MAX)) : false;
	unlink($config);
	if (!$cert || !openssl_x509_export($cert, $cert_pem) || !openssl_pkey_export($key, $key_pem)) {
		return 'Could not create a self-signed certificate: ' . openssl_error_string();
	}
	$certs = $data_path . '/certs';
	return sites_write($certs . '/default.key', $key_pem) && chmod($certs . '/default.key', 0600) && sites_write($certs . '/default.crt', $cert_pem)
		? '' : 'Could not write the certificate to: ' . $certs;
}

// From the command line (init.sh)
if (PHP_SAPI === 'cli' && isset($argv[0]) && realpath($argv[0]) === __FILE__) {
	if (!isset($argv[1], $argv[2]) || !is_dir($argv[2])) {
		fwrite(STDERR, "Usage: php sites.php generate|selfsigned <data path>\n");
		exit(1);
	}
	$error = $argv[1] === 'selfsigned' ? sites_selfsigned($argv[2]) : sites_generate($argv[2]);
	if ($error !== '') {
		fwrite(STDERR, $error . "\n");
		exit(1);
	}
}
