<?php
// Generates Nginx's sites for the proxied apps (sites/60-app-<name>.conf), the user's sites set up on the page (sites/
// 50-site-<name>.conf), the start page listing them (sites/00-app-start.conf and www/start/index.html, at apps.<domain>),
// and a temporary self-signed certificate. The domain itself shows one of the apps - the "home" app, by default the NAS's
// dashboard (gui) - or the start page when there's none. Used by the management page, and by init.sh through
// the NAS's own PHP CLI (WD's PHP 7.4, or the PHP app's 8.5), so it must work on both:
//     php sites.php generate <data path>
//     php sites.php selfsigned <data path>
// and by other apps and the Store, to add their own site (or update it - a name used for another target is refused),
// remove it, or find its address (the caller reloads Nginx afterwards: sh <nginx app>/nginx_ctl.sh reload):
//     php sites.php add-app <data path> <name> <target> [<label>] [--uploads] [--stream] [--host=<host>] [--path=<path>]
//     php sites.php remove-app <data path> <name>
//     php sites.php url <data path> <name>
// Settings live in <data path>/apps.json; sites written by the app start with SITES_MARKER, and only those are ever
// replaced or removed - everything else in sites/ belongs to the user.

const SITES_MARKER = '# Generated by the Nginx app (from its page in the NAS dashboard) - changes here are overwritten';
// The start page's name (apps.<domain>), which apps and sites can't use
const SITES_START_NAME = 'apps';

// The apps offered by default, when installed (their folder in Nas_Prog, if they have one): name => [label, target,
