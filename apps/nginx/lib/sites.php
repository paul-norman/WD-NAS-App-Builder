/**
 * A declaration with every field, if it's valid. auth_file is a password file the app keeps (an htpasswd file, readable
 * by Nginx's workers - nobody and its group), relative to Nas_Prog (e.g. _kvweb/htpasswd): its site then asks for a
 * user name and password before anything is passed on, and refuses everything while the file is missing.
 *
 * @param mixed  $declared  The declaration (e.g. an app's nginx.json)
 * @param string $apps_path Nas_Prog (for auth_file)
 *
 * @return array<string, mixed>|null The declaration, or null if it isn't valid
 */
function sites_declaration($declared, string $apps_path = ''): ?array
{
    if (!is_array($declared)) {
        return null;
    }

    $app = [
        'name'      => '',
        'label'     => '',
        'target'    => '',
        'host'      => '',
        'path'      => '',
        'start'     => '',
        'stream'    => false,
        'uploads'   => false,
        'auth_file' => ''
    ];

    foreach ($app as $key => $default) {
        if (isset($declared[$key])) {
            if (is_bool($default) ? !is_bool($declared[$key]) : !is_string($declared[$key])) {
                return null;
            }

            $app[$key] = $declared[$key];
        }
    }

    $app['name'] = strtolower($app['name']);
    $app['target'] = rtrim($app['target'], '/');

    if ($app['label'] === '') {
        $app['label'] = $app['name'];
    }

    if ($app['auth_file'] !== '' && (!preg_match('#^_[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$#', $app['auth_file']) || strpos($app['auth_file'], '..') !== false)) {
        return null;
    }

    $app['auth'] = $app['auth_file'] !== '' ? $apps_path.'/'.$app['auth_file'] : '';

    unset($app['auth_file']);

    return sites_check_app($app) === '' ? $app : null;
}

/**
 * A recipe's declarations, from its recipe.json. Its web block's site (port, path - where it opens - and nginx: name,
 * uploads, stream) has the folder's id; each of web.sites (name, label, port, path, uploads, stream, and if: the
 * boolean setting that switches its app on - read from its install record) has <folder>:<name>.
 *
 * @param string $folder The recipe's folder in Nas_Prog
 *
 * @return array<string, array<string, mixed>> Id => declaration
 */
function sites_recipe_declarations(string $folder): array
{
    $installed = json_decode((string)@file_get_contents($folder.'/.store/installed.json'), true);

    if (!is_array($installed)) {
        return [];
    }

    $recipe   = json_decode((string)@file_get_contents($folder.'/.store/recipe/recipe.json'), true);
    $web      = is_array($recipe) && isset($recipe['web']) && is_array($recipe['web']) ? $recipe['web'] : [];
    $values   = isset($installed['values']) && is_array($installed['values']) ? $installed['values'] : [];
    $id       = basename($folder);
    $declared = [];

    if (isset($web['nginx']['name'], $web['port']) && is_int($web['port'])) {
        $path          = isset($web['path']) && is_string($web['path']) ? $web['path'] : '';
        $declared[$id] = sites_declaration([
            'name'    => $web['nginx']['name'],
            'label'   => isset($recipe['name']) && is_string($recipe['name']) ? $recipe['name'] : '',
            'target'  => 'http://127.0.0.1:'.$web['port'],
            'start'   => $path !== '/' ? $path : '',
            'stream'  => !empty($web['nginx']['stream']),
            'uploads' => !empty($web['nginx']['uploads']),
        ]);
    }

    foreach (isset($web['sites']) && is_array($web['sites']) ? $web['sites'] : [] as $site) {
        if (!is_array($site) || !isset($site['name'], $site['port']) || !is_string($site['name']) || !is_int($site['port'])) {
            continue;
        }

        // Switched off: true or "on" - as the Store records a boolean setting - is on
        if (isset($site['if']) && (!is_string($site['if']) || !isset($values[$site['if']]) || !in_array($values[$site['if']], [true, 'on', 'true', 1, '1'], true))) {
            continue;
        }

        $path = isset($site['path']) && is_string($site['path']) ? $site['path'] : '';

        $declared[$id.':'.$site['name']] = sites_declaration([
            'name'    => $site['name'],
            'label'   => isset($site['label']) && is_string($site['label']) ? $site['label'] : '',
            'target'  => 'http://127.0.0.1:'.$site['port'],
            'start'   => $path !== '/' ? $path : '',
            'stream'  => !empty($site['stream']),
            'uploads' => !empty($site['uploads']),
        ]);
    }

    return array_filter($declared);
}

/**
 * Every declared app that's installed: from its nginx.json, its recipe.json (recipes installed by the Store), or the
 * built-in list.
 *
 * @param string $data_path The Nginx app's data folder
 *
 * @return array<string, array<string, mixed>> Its id (its folder in Nas_Prog, 'gui' for the dashboard) => its
 *                                             declaration
 */
function sites_declared(string $data_path): array
{
    $apps_path = dirname($data_path);
    $builtin   = sites_builtin_apps();
    $declared  = ['gui' => sites_declaration($builtin[''])];

    foreach (glob($apps_path.'/*', GLOB_ONLYDIR) ?: [] as $folder) {
        $id = basename($folder);

        if ($id === 'gui') {
            continue;
        }

        if (is_file($folder.'/nginx.json')) {
            $app = sites_declaration(json_decode((string)@file_get_contents($folder.'/nginx.json'), true), $apps_path);
        } elseif (is_dir($folder.'/.store')) {
            // A recipe may have several sites
            $declared += sites_recipe_declarations($folder);

            continue;
        } else {
            $app = isset($builtin[$id]) ? sites_declaration($builtin[$id]) : null;
        }

        if ($app !== null) {
            $declared[$id] = $app;
        }
    }

    return $declared;
}

/**
 * A saved app's settings with its declaration's, for an app that has one: the user's choices (on, name, label) and the
 * rest from its declaration.
 *
 * @param mixed                $id       The app's id (an array key: a folder named with digits is an int)
 * @param array<string, mixed> $app      Its saved settings
 * @param array<string, mixed> $declared Its declaration
 *
 * @return array<string, mixed> The app's settings
 */
function sites_declared_app($id, array $app, array $declared): array
{
    $entry = [
        'app'     => $id,
        'name'    => $app['name'],
        'label'   => $app['label'] !== '' ? $app['label'] : $declared['label'],
        'enabled' => !empty($app['enabled'])
    ];

    foreach (SITES_DECLARATION_FIELDS as $key) {
        $entry[$key] = $declared[$key];
    }

    return $entry;
}

/**
 * The settings (apps.json), with every declared app that's installed: saved apps matched to their declarations (by name
 * and target, then by target and path - they may have been renamed), those of apps no longer installed put aside (and
 * back when they are), and newly installed apps added under their own name (with a number added if it's taken).
 *
 * @param string $data_path The Nginx app's data folder
 *
 * @return array{
 *     domain:  string,
 *     home:    string,
 *     apps:    list<array<string, mixed>>,
 *     sites:   list<array<string, mixed>>,
 *     dormant: list<array<string, mixed>>,
 * } The settings
 */
function sites_load(string $data_path): array
{
    $settings = json_decode((string)@file_get_contents($data_path.'/apps.json'), true);

    if (!is_array($settings)) {
        $settings = [];
    }

    $settings += ['domain' => '', 'home' => 'gui', 'apps' => [], 'sites' => [], 'dormant' => []];
    $declared = sites_declared($data_path);
    $saved    = [];

    foreach ($settings['apps'] as $app) {
        if (is_array($app) && isset($app['name'], $app['target'])) {
            $saved[] = $app + ['label' => '', 'host' => '', 'path' => '', 'start' => '', 'stream' => false, 'uploads' => false, 'auth' => '', 'enabled' => true];
        }
    }

    // Apps saved before they were declared (or this was) are matched to their declaration: by name and target, then
    // by target and path (they may have been renamed)
    $claimed = [];

    foreach ($saved as $app) {
        if (isset($app['app']) && is_string($app['app'])) {
            $claimed[$app['app']] = true;
        }
    }

    foreach ([true, false] as $by_name) {
        foreach ($saved as $i => $app) {
            if (isset($app['app'])) {
                continue;
            }

            foreach ($declared as $id => $declaration) {
                if (!isset($claimed[$id]) && rtrim($app['target'], '/') === $declaration['target']
                    && ($by_name ? $app['name'] === $declaration['name'] : $app['path'] === $declaration['path'])) {
                    $saved[$i]['app'] = $id;
                    $claimed[$id]     = true;

                    break;
                }
            }
        }
    }

    // Those of apps no longer installed are put aside (and back when they are)
    $dormant = [];

    foreach (array_merge($settings['dormant'], $saved) as $app) {
        if (is_array($app) && isset($app['app'], $app['name']) && is_string($app['app'])) {
            $dormant[$app['app']] = [
                'app'     => $app['app'],
                'name'    => (string)$app['name'],
                'label'   => isset($app['label']) ? (string)$app['label'] : '',
                'enabled' => !empty($app['enabled'])
            ];
        }
    }

    $apps  = [];
    $names = [];

    foreach ($saved as $app) {
        if (!isset($app['app'])) {
            $apps[] = $app;
        } elseif (isset($declared[$app['app']]) && isset($dormant[$app['app']])) {
            $apps[] = sites_declared_app($app['app'], $app, $declared[$app['app']]);

            unset($dormant[$app['app']]);
        }
    }

    foreach (array_merge($apps, $settings['sites']) as $app) {
        $names[$app['name']] = true;
    }

    // Newly installed apps: offered under their own name (or, if that's taken, with a number added)
    foreach ($declared as $id => $declaration) {
        if (!isset($claimed[$id]) || isset($dormant[$id])) {
            $app = isset($dormant[$id]) ? $dormant[$id] : ['name' => $declaration['name'], 'label' => '', 'enabled' => true];

            for ($n = 2, $name = $app['name']; isset($names[$app['name']]); $n++) {
                $app['name'] = substr($name, 0, 60).'-'.$n;
            }

            $names[$app['name']] = true;

            $apps[] = sites_declared_app($id, $app, $declaration);

            unset($dormant[$id]);
        }
    }

    $settings['apps']    = sites_sorted($apps);
    $settings['sites']   = sites_sorted($settings['sites']);
    $settings['dormant'] = array_values($dormant);

    return $settings;
}

/**
 * Apps or sites in alphabetical order of their labels (ignoring case, numbers in order: "App 2" before "App 10").
 *
 * @param list<array<string, mixed>> $list The apps or sites
 *
 * @return list<array<string, mixed>> The same, in order
 */
function sites_sorted(array $list): array
{
    usort($list, function (array $a, array $b): int {
        return strnatcasecmp($a['label'] !== '' ? $a['label'] : $a['name'], $b['label'] !== '' ? $b['label'] : $b['name'])
            ?: strcmp($a['name'], $b['name']);
    });

    return $list;
}

/**
 * The app shown at the domain itself, if it's switched on and valid - the start page is shown there otherwise.
 *
 * @param array<string, mixed> $settings The settings (see sites_load())
 *
 * @return array<string, mixed>|null The app, or null
 */
function sites_home_app(array $settings): ?array
{
    foreach ($settings['apps'] as $app) {
        if ($settings['home'] !== '' && $app['name'] === $settings['home'] && $app['enabled'] && sites_check_app($app) === '') {
            return $app;
        }
    }

    return null;
}

/**
 * An app's or site's host name: <name>.<domain>, or the domain itself for the home app.
 *
 * @param array<string, mixed> $settings The settings (see sites_load())
 * @param array<string, mixed> $app      The app or site
 *
 * @return string The host name
 */
function sites_host(array $settings, array $app): string
{
    $home = sites_home_app($settings);

    return $home !== null && $home['name'] === $app['name'] && isset($app['target']) ? $settings['domain'] : $app['name'].'.'.$settings['domain'];
}

/**
 * Saves the settings (apps.json).
 *
 * @param string               $data_path The Nginx app's data folder
 * @param array<string, mixed> $settings  The settings
 *
 * @return bool Whether they were saved
 */
function sites_save(string $data_path, array $settings): bool
{
    return sites_write($data_path.'/apps.json', json_encode($settings, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");
}

/**
 * Adds an app's site, or updates it (keeping whether it's switched on) - refusing a name another app or site uses -
 * then writes the sites. A declared app's site is its declaration's (see sites_declared()), so it's left as it is.
 *
 * @param string               $data_path The Nginx app's data folder
 * @param array<string, mixed> $app       The app: name and target, and optionally label, host, path, start, stream and
 *                                        uploads
 *
 * @return string '' or an error message
 */
function sites_add_app(string $data_path, array $app): string
{
    $app += ['label' => '', 'host' => '', 'path' => '', 'start' => '', 'stream' => false, 'uploads' => false, 'auth' => ''];

    $app['name']   = strtolower($app['name']);
    $app['target'] = rtrim($app['target'], '/');

    if ($app['label'] === '') {
        $app['label'] = $app['name'];
    }

    if (($error = sites_check_app($app)) !== '') {
        return $error;
    }

    $settings = sites_load($data_path);

    foreach ($settings['sites'] as $site) {
        if ($site['name'] === $app['name']) {
            return 'A site already uses this name: '.$app['name'];
        }
    }

    $entry = [
        'name'    => $app['name'],
        'label'   => $app['label'],
        'target'  => $app['target'],
        'host'    => $app['host'],
        'path'    => $app['path'],
        'start'   => $app['start'],
        'stream'  => (bool)$app['stream'],
        'uploads' => (bool)$app['uploads'],
        'enabled' => true,
    ];

    $found = false;

    foreach ($settings['apps'] as $i => $existing) {
        if ($existing['name'] === $app['name']) {
            if (rtrim($existing['target'], '/') !== $entry['target']) {
                return 'Another app already uses this name: '.$app['name'].' ('.$existing['target'].')';
            }

            if (isset($existing['app'])) {
                return sites_generate($data_path);
            }

            $entry['enabled']     = $existing['enabled'];
            $settings['apps'][$i] = $entry;

            $found = true;
        }
    }

    if (!$found) {
        $settings['apps'][] = $entry;
    }

    return sites_save($data_path, $settings) ? sites_generate($data_path) : 'Could not save the apps';
}

/**
 * Removes an app's site, then writes the sites. A declared app's goes when its app does, so it's left as it is.
 *
 * @param string $data_path The Nginx app's data folder
 * @param mixed  $name      The app's site's name
 *
 * @return string '' or an error message
 */
function sites_remove_app(string $data_path, $name): string
{
    $settings = sites_load($data_path);

    foreach ($settings['apps'] as $i => $app) {
        if ($app['name'] === $name && !isset($app['app'])) {
            unset($settings['apps'][$i]);
        }
    }

    $settings['apps'] = array_values($settings['apps']);

    return sites_save($data_path, $settings) ? sites_generate($data_path) : 'Could not save the apps';
}

/**
 * An app's address: https://<name>.<domain>/ with its path or start page.
 *
 * @param string $data_path The Nginx app's data folder
 * @param mixed  $name      The app's site's name
 *
 * @return string The address, or '' while it has none (no domain, switched off, or not listed)
 */
function sites_app_url(string $data_path, $name): string
{
    $settings = sites_load($data_path);

    foreach ($settings['apps'] as $app) {
        if ($app['name'] === $name && $app['enabled'] && $settings['domain'] !== '') {
            return 'https://'.sites_host($settings, $app).($app['path'] !== '' ? $app['path'] : ($app['start'] !== '' ? $app['start'] : '/'));
        }
    }

    return '';
}

/**
 * Checks one app's settings: its name, target, host, path, password file, start page and label.
 *
 * @param array<string, mixed> $app The app
 *
 * @return string '' or an error message
 */
function sites_check_app(array $app): string
{
    if (!preg_match('/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/', $app['name'])) {
        return 'Names are lower case letters, digits and - (e.g. jellyfin): '.$app['name'];
    }

    if ($app['name'] === SITES_START_NAME) {
        return SITES_START_NAME.' is the start page\'s name ('.SITES_START_NAME.'.<domain>) - choose another';
    }

    if (!preg_match('#^https?://[A-Za-z0-9.-]+(:\d{1,5})?$#', $app['target'])) {
        return 'Targets are an address and port, e.g. http://127.0.0.1:8096 (for '.$app['name'].')';
    }

    if ($app['host'] !== '' && !preg_match('/^[A-Za-z0-9.-]+(:\d{1,5})?$/', $app['host'])) {
        return 'Not a host name, for '.$app['name'].': '.$app['host'];
    }

    if ($app['path'] !== '' && !preg_match('#^/[A-Za-z0-9._~/-]*/$#', $app['path'])) {
        return 'Paths start and end with /, e.g. /phpMyAdmin/ (for '.$app['name'].')';
    }

    // Only ever set by an app's declaration - see sites_declaration
    if (isset($app['auth']) && $app['auth'] !== '' && (!preg_match('#^/[A-Za-z0-9._/-]+$#', $app['auth']) || strpos($app['auth'], '..') !== false)) {
        return 'Not a password file, for '.$app['name'];
    }

    if ($app['start'] !== '' && !preg_match('#^/[A-Za-z0-9._~/-]*$#', $app['start'])) {
        return 'Start pages start with /, e.g. /admin/ (for '.$app['name'].')';
    }

    if (mb_strlen($app['label']) > 60 || preg_match('/[\x00-\x1f]/', $app['label'])) {
        return 'Labels are up to 60 characters, for '.$app['name'];
    }

    return '';
}

/**
 * Checks one of the user's sites: its name, its folder (on the NAS's volumes or USB drives, really - not through a
 * link) and its label.
 *
 * @param array<string, mixed> $site The site
 *
 * @return string '' or an error message
 */
function sites_check_site(array $site): string
{
    if (!preg_match('/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/', $site['name'])) {
        return 'Names are lower case letters, digits and - (e.g. blog): '.$site['name'];
    }

    if ($site['name'] === SITES_START_NAME) {
        return SITES_START_NAME.' is the start page\'s name ('.SITES_START_NAME.'.<domain>) - choose another';
    }

    // No quotes, ; { } $ or \, which would break out of Nginx's configuration
    if (!preg_match('#^/(mnt/HD|mnt/USB|shares)/[^"\';{}$\\\\\x00-\x1f]+$#', $site['root'])) {
        return 'Folders are on the NAS\'s volumes or USB drives, e.g. /mnt/HD/HD_a2/Web/blog (for '.$site['name'].')';
    }

    if (!is_dir($site['root'])) {
        return 'No such folder, for '.$site['name'].': '.$site['root'];
    }

    // Where it really is (e.g. not /mnt/HD/../etc)
    if (!preg_match('#^/(mnt/HD|mnt/USB)/#', realpath($site['root']).'/')) {
        return 'Folders are on the NAS\'s volumes or USB drives, for '.$site['name'].': '.$site['root'];
    }

    if (mb_strlen($site['label']) > 60 || preg_match('/[\x00-\x1f]/', $site['label'])) {
        return 'Labels are up to 60 characters, for '.$site['name'];
    }

    return '';
}

/**
 * Checks a domain name (e.g. example.com or nas.example.com).
 *
 * @param string $domain The domain
 *
 * @return string '' or an error message
 */
function sites_check_domain(string $domain): string
{
    return preg_match('/^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/', $domain) ? '' : 'Not a domain name (e.g. example.com or nas.example.com): '.$domain;
}

/**
 * Writes a file in one step (a temporary file renamed over it).
 *
 * @param string $file     The file
 * @param string $contents What it holds
 *
 * @return bool Whether it was written
 */
function sites_write(string $file, string $contents): bool
{
    $temp = $file.'.tmp';

    return file_put_contents($temp, $contents) !== false && rename($temp, $file);
}

/**
 * One app's site: a proxy to its target, with its options - a password, streaming (no buffering) and uploads (no size
 * limit), with longer timeouts for either - under its path, or everything with / going to its start page. The NAS's
 * dashboard's site also gets the script that opens an app's page from the start page's Configure links (see
 * dashboard.js): added to its pages, and served by Nginx itself.
 *
 * @param array<string, mixed> $app         The app
 * @param string               $server_name Its name: <name>.<domain>, or the domain for the home app
 *
 * @return string The site's configuration
 */
function sites_app_conf(array $app, string $server_name): string
{
    $dashboard = ($app['app'] ?? '') === 'gui';

    $host = $app['host'] !== '' ? $app['host'] : '$host';

    // An app that asks for a password through Nginx: see sites_declaration
    $proxy = (!empty($app['auth']) ? "        auth_basic           \"{$app['name']}\";\n        auth_basic_user_file {$app['auth']};\n" : '')
       ."        include          server.d/proxy.conf;\n"
       ."        proxy_set_header Host {$host};\n"
       ."        proxy_pass       {$app['target']};\n";

    // The dashboard's pages, uncompressed (for Nginx to add the script before </head>)
    if ($dashboard) {
        $proxy .= "        proxy_set_header Accept-Encoding \"\";\n"
           ."        sub_filter       '</head>' '<script src=\"/nginx-app-dashboard.js\"></script></head>';\n"
           ."        sub_filter_once  on;\n";
    }

    // Its options (see sites_declared) - both can be on, so each directive is written once
    if (!empty($app['stream'])) {
        $proxy .= "        proxy_buffering         off;\n";
    }

    if (!empty($app['uploads'])) {
        $proxy .= "        client_max_body_size    0;\n";
    }

    if (!empty($app['stream']) || !empty($app['uploads'])) {
        $timeout = !empty($app['uploads']) ? '10m' : '3m';
        $proxy .= "        proxy_request_buffering off;\n"
           ."        proxy_read_timeout      {$timeout};\n"
           ."        proxy_send_timeout      {$timeout};\n";
    }
    // Under a path, only it is passed on (e.g. phpMyAdmin's, on the NAS's own web server); a start page is only where /
    // goes, with every path passed on (e.g. Pi-hole's /admin/, whose pages call its /api)
    $start     = $app['path'] !== '' ? $app['path'] : $app['start'];
    $locations = ($dashboard ? "    location = /nginx-app-dashboard.js {\n        alias ".__DIR__."/dashboard.js;\n    }\n\n" : '')
       .($start !== '' && $start !== '/' ? "    location = / {\n        return 302 {$start};\n    }\n\n" : '')
       .'    location '.($app['path'] !== '' ? $app['path'] : '/')." {\n{$proxy}    }\n";

    return SITES_MARKER."\n# {$app['label']}\n\nserver {\n"
       ."    include     server.d/https.conf;\n"
       ."    server_name {$server_name};\n\n"
       .$locations."}\n";
}

/**
 * One of the user's sites: its folder, with PHP (or with PHP files refused, so that their source is never shown), and
 * optionally with every unknown path going to index.php (front controllers, e.g. Laravel, WordPress).
 *
 * @param array<string, mixed> $site   The site
 * @param string               $domain The domain
 *
 * @return string The site's configuration
 */
function sites_site_conf(array $site, string $domain): string
{
    $root     = rtrim($site['root'], '/');
    $fallback = $site['php'] && $site['front'] ? '/index.php?$query_string' : '=404';

    return SITES_MARKER."\n# {$site['label']}\n\nserver {\n"
       ."    include     server.d/https.conf;\n"
       ."    server_name {$site['name']}.{$domain};\n"
       ."    root        \"{$root}\";\n"
       .'    index       '.($site['php'] ? 'index.php ' : '')."index.html index.htm;\n\n"
       ."    include     server.d/hidden.conf;\n"
       ."    include     server.d/log-exclusions.conf;\n"
       .'    include     server.d/'.($site['php'] ? 'php.conf' : 'php-off.conf').";\n\n"
       ."    location / {\n        try_files \$uri \$uri/ {$fallback};\n    }\n}\n";
}

/**
 * The start page's site (apps.<domain>, and the domain itself without a home app): also the default for any other name,
 * and where HTTP/3's reuseport is set (it's only allowed once).
 *
 * @param string $domain    The domain ('' while there's none)
 * @param string $data_path The Nginx app's data folder
 * @param bool   $at_domain Whether it's also at the domain itself (no home app)
 *
 * @return string The site's configuration
 */
function sites_start_conf(string $domain, string $data_path, bool $at_domain): string
{
    $names = $domain !== '' ? SITES_START_NAME.'.'.$domain.' '.($at_domain ? $domain.' ' : '') : '';

    return SITES_MARKER."\n# The start page, listing the apps (and the answer for any name without a site)\n\nserver {\n"
       ."    listen      443 ssl default_server;\n"
       ."    listen      443 quic reuseport default_server;\n"
       ."    http2       on;\n"
       ."    add_header  Alt-Svc 'h3=\":443\"; ma=86400' always;\n"
       ."    server_name {$names}_;\n"
       ."    root        {$data_path}/www/start;\n"
       ."    index       index.html;\n\n"
       ."    include     ssl.d/default.conf;\n"
       ."    include     server.d/hidden.conf;\n"
       ."    include     server.d/log-exclusions.conf;\n\n"
       ."    location / {\n        try_files \$uri \$uri/ =404;\n    }\n}\n";
}

/**
 * An installed app's own page in the NAS dashboard (its Configure page): its index page, when its apkg.rc shows one
 * there (CenterType 1). Recipes, the dashboard itself and apps packaged without one have none.
 *
 * @param string $apps_path Nas_Prog
 * @param mixed  $id        The app's id (its folder in Nas_Prog)
 *
 * @return string Its index page (e.g. index.php), or ''
 */
function sites_configure_page(string $apps_path, $id): string
{
    if (!is_string($id) || !preg_match('/^[A-Za-z0-9._-]+$/', $id) || $id === 'gui' || $id[0] === '.') {
        return '';
    }

    $rc = (string)@file_get_contents($apps_path.'/'.$id.'/apkg.rc');

    if (!preg_match('/^CenterType:[ \t]*1[ \t]*$/m', $rc) || !preg_match('/^AddonIndexPage:[ \t]*([A-Za-z0-9._-]+)[ \t]*$/m', $rc, $m)) {
        return '';
    }

    return $m[1];
}

/**
 * The recipe a site belongs to, for one installed by the Store: its folder in Nas_Prog (a recipe's sites' ids are
 * <folder> or <folder>:<site>), with its install record (.store/installed.json: its id in the Store) and its name.
 *
 * @param string $apps_path Nas_Prog
 * @param mixed  $id        The site's app id
 *
 * @return array{folder: string, id: string, name: string}|null The recipe, or null for an app's site
 */
function sites_recipe(string $apps_path, $id): ?array
{
    $folder = is_string($id) ? explode(':', $id)[0] : '';

    if (!preg_match('/^[A-Za-z0-9_-][A-Za-z0-9._-]*$/', $folder) || !is_dir($apps_path.'/'.$folder.'/.store')) {
        return null;
    }

    $installed = json_decode((string)@file_get_contents($apps_path.'/'.$folder.'/.store/installed.json'), true);
    $recipe    = json_decode((string)@file_get_contents($apps_path.'/'.$folder.'/.store/recipe/recipe.json'), true);
    $store_id  = is_array($installed) && isset($installed['id']) && is_string($installed['id']) ? $installed['id'] : '';

    return [
        'folder' => $folder,
        'id'     => preg_match('/^[A-Za-z0-9_-][A-Za-z0-9._-]*$/', $store_id) ? $store_id : '',
        'name'   => is_array($recipe) && isset($recipe['name']) && is_string($recipe['name']) && $recipe['name'] !== '' ? $recipe['name'] : $folder,
    ];
}

/**
 * An app's Configure link on the start page: its own page in the NAS dashboard (see sites_configure_page()) - the
 * dashboard's address with #configure=<id>/<page>, which the script added to the dashboard's pages opens (see
 * dashboard.js). A recipe's link (#recipe=<id>, its page in the Store) is its section's, on the start page.
 *
 * @param string $apps_path Nas_Prog
 * @param mixed  $id        The app's id (its folder in Nas_Prog)
 * @param string $dashboard The dashboard's address (its site's), or '' while it has none
 *
 * @return string The link, or '' for none
 */
function sites_configure_link(string $apps_path, $id, string $dashboard): string
{
    $page = $dashboard !== '' && is_string($id) ? sites_configure_page($apps_path, $id) : '';

    return $page !== '' ? $dashboard.'#configure='.rawurlencode((string)$id).'/'.rawurlencode($page) : '';
}

/**
 * Copies the apps' icons (from their packages: apkg.rc's Icon, in their web folder) next to the start page, as
 * icons/<id>.<type>, removing those of apps no longer listed. Only SVG, PNG, JPEG, GIF and WebP icons up to 256KB.
 *
 * @param string                     $data_path The Nginx app's data folder
 * @param list<array<string, mixed>> $apps      The apps listed
 *
 * @return array<string, string> Id => its icon's file, in icons/
 */
function sites_start_icons(string $data_path, array $apps): array
{
    $apps_path = dirname($data_path);
    $dir       = $data_path.'/www/start/icons';
    $icons     = [];

    if (!is_dir($dir) && !@mkdir($dir, 0755, true)) {
        return [];
    }

    foreach ($apps as $app) {
        $id = isset($app['app']) && is_string($app['app']) ? $app['app'] : '';

        if (!preg_match('/^[A-Za-z0-9_-][A-Za-z0-9._-]*$/', $id)) {
            continue;
        }

        $rc = (string)@file_get_contents($apps_path.'/'.$id.'/apkg.rc');

        if (!preg_match('/^Icon:[ \t]*([A-Za-z0-9._-]+\.(svg|png|jpe?g|gif|webp))[ \t]*$/mi', $rc, $m)) {
            continue;
        }

        $source = $apps_path.'/'.$id.'/web/'.$m[1];
        $file   = $id.'.'.strtolower($m[2]);

        if (is_file($source) && filesize($source) <= 262144 && @copy($source, $dir.'/'.$file)) {
            @chmod($dir.'/'.$file, 0644);
            $icons[$id] = $file;
        }
    }

    foreach (glob($dir.'/*') ?: [] as $file) {
        if (!in_array(basename($file), $icons, true)) {
            @unlink($file);
        }
    }

    return $icons;
}

